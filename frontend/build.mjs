import { build } from "esbuild";
import { existsSync, readdirSync, rmSync } from "node:fs";
import { resolve } from "node:path";
import { updateModulePreloads } from "./build/preloads.mjs";
const shared = {
  bundle: true,
  minify: true,
  jsx: "automatic",
  define: { "process.env.NODE_ENV": '"production"' },
  entryNames: "[name]",
  legalComments: "eof",
  banner: {
    js: "/* Generated by frontend/build.mjs. Edit frontend/ source, then run npm run build. */",
    css: "/* Generated by frontend/build.mjs. Edit frontend/ source, then run npm run build. */",
  },
};
await build({
  ...shared,
  entryPoints: ["frontend/home.jsx"],
  outdir: "src/main/resources/static/javascript/darkveil",
});
const uiBuild = await build({
  ...shared,
  metafile: true,
  format: "esm",
  splitting: true,
  chunkNames: "chunks/[name]-[hash]",
  entryPoints: [
    "frontend/navigation.jsx",
    "frontend/auth.jsx",
    "frontend/workspace.jsx",
    "frontend/social.jsx",
    "frontend/account.jsx",
    "frontend/suggestion.jsx",
    "frontend/catalog.jsx",
    "frontend/calendar.jsx",
    "frontend/booking.jsx",
    "frontend/openclaw.jsx",
  ],
  outdir: "src/main/resources/static/javascript/ui",
});

await build({
  ...shared,
  entryPoints: ["frontend/booking-nav.jsx"],
  outfile:
    process.env.BOOKING_ASSET_FILE ||
    (existsSync("booking/school")
      ? "booking/school/aero-shards.bundle.js"
      : existsSync("../outputs/qpsw-mrbs/school")
        ? "../outputs/qpsw-mrbs/school/aero-shards.bundle.js"
        : "src/main/resources/static/javascript/booking/aero-shards.bundle.js"),
  format: "iife",
});

// Templates preload shared chunks without changing the lazy-loading boundaries.
await updateModulePreloads("src/main/resources/templates", uiBuild.metafile.outputs);

// Only delete obsolete generated chunks after a successful build and template update.
const generatedChunks = "src/main/resources/static/javascript/ui/chunks";
const currentOutputs = new Set(Object.keys(uiBuild.metafile.outputs).map((path) => resolve(path)));
if (existsSync(generatedChunks)) {
  for (const name of readdirSync(generatedChunks)) {
    const path = `${generatedChunks}/${name}`;
    if (/\.(js|css|map)$/.test(name) && !currentOutputs.has(resolve(path))) rmSync(path);
  }
}
